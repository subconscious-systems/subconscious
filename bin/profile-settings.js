import {
  AGENTS,
  agentInputs,
  DEFAULTS,
  PACKAGED_MODELS,
  resolveRefs,
  SHARED_INPUTS,
  staticLookup,
} from './agent-data.js';

export const SUPPORTED_MODELS = Object.freeze([...PACKAGED_MODELS]);

const TOKEN = /\{[A-Za-z][A-Za-z0-9]*\}/;
const shown = (input) => input.label && input.group !== 'shared';

function toSetting(input) {
  const model = input.type === 'model';
  const setting = {
    key: input.name,
    label: input.label,
    description: input.description,
    type: model ? 'choice' : input.type || 'text',
  };
  if (model) Object.assign(setting, { choices: SUPPORTED_MODELS, model });
  if (input.choices) setting.choices = input.choices;
  for (const field of ['min', 'max', 'required'])
    if (input[field] !== undefined) setting[field] = input[field];
  return Object.freeze(setting);
}

function group(id, label, inputs) {
  return Object.freeze({
    id,
    label,
    keys: inputs.map((input) => input.name),
    settings: inputs.map(toSetting),
  });
}

export const PROFILE_SETTING_GROUPS = Object.freeze([
  group(
    'shared',
    'Shared settings',
    SHARED_INPUTS.filter((input) => input.group === 'shared'),
  ),
  ...AGENTS.map((agent) =>
    group(agent.id, agent.name, agentInputs(agent).filter(shown)),
  ),
]);

/** A default a profile can hold: literal, with references resolved. */
function profileDefault(input, lookup) {
  if (input.type === 'secret' || input.default === undefined) return '';
  const value = String(resolveRefs(input.default, lookup));
  return TOKEN.test(value) ? '' : value;
}

function agentDefaults(agent) {
  const lookup = staticLookup(agent);
  // A profile pins every default it holds, so inputs kept out of the
  // template stay out of new and existing profiles.
  return agentInputs(agent)
    .filter((input) => input.label && input.template !== false)
    .map((input) => [input.name, profileDefault(input, lookup)]);
}

export const RUNBOOK_DEFAULTS = Object.freeze({
  ...Object.fromEntries(AGENTS.flatMap(agentDefaults)),
  GATEWAY_URL: DEFAULTS.baseUrl,
  API_KEY: '',
  MODEL: DEFAULTS.model,
});

export function profileSettingsForAgent(agentId) {
  const shared = PROFILE_SETTING_GROUPS.find((item) => item.id === 'shared');
  const agent = PROFILE_SETTING_GROUPS.find((item) => item.id === agentId);
  return [...(shared?.settings || []), ...(agent?.settings || [])];
}

export function resolvedProfileValues(profile) {
  return { ...RUNBOOK_DEFAULTS, ...(profile?.values || {}) };
}

function templateLine(input) {
  const line = `${input.name}={${input.name}}`;
  return input.comment ? [`# ${input.comment}`, line] : [line];
}

function agentSections() {
  const written = new Set();
  return AGENTS.flatMap((agent) => {
    const inputs = agentInputs(agent).filter(
      (input) =>
        shown(input) &&
        input.type !== 'secret' &&
        input.template !== false &&
        !written.has(input.name),
    );
    for (const input of inputs) written.add(input.name);
    if (!inputs.length) return [];
    return ['', `# ${agent.name}`, ...inputs.flatMap(templateLine)];
  });
}

/** The new-profile file, with `{KEY}` where each value goes. */
export function profileTemplate() {
  const keys = AGENTS.flatMap((agent) =>
    agentInputs(agent).filter(
      (input) => shown(input) && input.type === 'secret',
    ),
  );
  return [
    '# Subconscious coding-agent profile',
    '# Generated by subc. Extra KEY=value lines are passed through to launches.',
    '',
    'GATEWAY_URL={GATEWAY_URL}',
    'API_KEY={API_KEY}',
    '# Available models (MODEL=UNSET uses the first live catalog model):',
    ...SUPPORTED_MODELS.map((model) => `#   ${model}`),
    'MODEL={MODEL}',
    '',
    '# Optional per-agent keys. Leave blank to use API_KEY above.',
    ...keys.map((input) => `${input.name}={${input.name}}`),
    ...agentSections(),
    '',
    '# Extra KEY=value lines are passed through to launches.',
    '',
  ].join('\n');
}
