# shellcheck shell=bash
# subc sets every value a runbook reads, so a runbook declares no defaults
# of its own.

# Exact IDs only: similarly named models do not inherit capabilities.
subc_model_supports_vision() {
  local model
  while IFS= read -r model; do
    [[ -n "$model" && "$model" == "${1:-}" ]] && return 0
  done <<< "${SUBC_VISION_MODELS:-}"
  return 1
}

# Quote a value for a line of shell source: ' becomes '\''.
#
# The shared secrets file below is sourced by hook.sh, so a value written into
# it has to survive being read back exactly. A single quote in a value is the
# one character that does not survive unquoted interpolation; everything else,
# including newlines and shell metacharacters, is already literal inside single
# quotes.
subc_shell_quote() {
  printf "'%s'" "${1//\'/\'\\\'\'}"
}

# One `export NAME=VALUE` line, quoted.
subc_env_line() {
  printf 'export %s=%s\n' "$1" "$(subc_shell_quote "$2")"
}

# ── Shared credentials ─────────────────────────────────────────────────────
#
# Each hook used to carry its own copy of the API key, in a file inside the
# agent's directory, so one key existed in up to five places. One shared file
# instead, so it exists once and a rotation is one edit. Override the location
# with SUBCONSCIOUS_SECRETS_FILE.
subc_secrets_file() {
  printf '%s' "${SUBCONSCIOUS_SECRETS_FILE:-${HOME}/.subconscious/secrets.env}"
}

# Write the gateway and key to the shared file. Prints its path.
subc_write_shared_secrets() {
  local file dir
  file="$(subc_secrets_file)"
  dir="$(dirname "$file")"
  mkdir -p "$dir"
  chmod 700 "$dir"
  umask 077
  {
    echo '# Generated by subc — do not commit secrets.'
    subc_env_line SUBCONSCIOUS_GATEWAY_URL "${GATEWAY_URL%/}"
    subc_env_line SUBCONSCIOUS_API_KEY "$API_KEY"
  } >"$file"
  chmod 600 "$file"
  printf '%s' "$file"
}

# What an agent directory holds instead of the key: the gateway origin, which
# is not a secret, plus a pointer to the file that has the key. Keeping the
# gateway here means a hook never ends up with a key but no endpoint.
subc_write_secrets_pointer() {
  local target dir
  target="$1"
  dir="$(dirname "$target")"
  mkdir -p "$dir"
  umask 077
  {
    echo '# Generated by subc — do not commit secrets.'
    echo '# The API key lives in the file named below. Treat that file as a secret.'
    subc_env_line SUBCONSCIOUS_GATEWAY_URL "${GATEWAY_URL%/}"
    subc_env_line SUBCONSCIOUS_SECRETS_FILE "$(subc_secrets_file)"
  } >"$target"
  chmod 600 "$target"
}

# Resolve the key once the agent-local env file has been sourced. An older
# install still names the key inline, so an inline value wins and the pointer is
# followed only when the key is still unset.
subc_follow_secrets_pointer() {
  [[ -n "${SUBCONSCIOUS_API_KEY:-}" ]] && return 0
  [[ -n "${SUBCONSCIOUS_SECRETS_FILE:-}" ]] || return 0
  [[ -f "$SUBCONSCIOUS_SECRETS_FILE" ]] || return 0
  # shellcheck disable=SC1090
  source "$SUBCONSCIOUS_SECRETS_FILE"
}

# Replace this shell with the agent argv subc built:
#   subc_exec [PLACEHOLDER VALUE]... -- ARGV...
# Only the first SUBC_TEMPLATE_WORDS words came from the agent's argv
# template; passed-through arguments and the prompt after them are never
# rewritten, whatever they contain.
subc_exec() {
  local names=() values=() argv=() word index=0 i
  while [[ $# -gt 0 && "$1" != "--" ]]; do
    names+=("$1")
    values+=("$2")
    shift 2
  done
  shift
  local limit="${SUBC_TEMPLATE_WORDS:-0}"
  unset SUBC_TEMPLATE_WORDS SUBC_MODEL_IDS SUBC_VISION_MODELS
  for word in "$@"; do
    if [[ "$index" -lt "$limit" ]]; then
      for ((i = 0; i < ${#names[@]}; i++)); do
        if [[ "$word" == *"${names[i]}"* ]]; then
          word="${word%%"${names[i]}"*}${values[i]}${word#*"${names[i]}"}"
        fi
      done
    fi
    argv+=("$word")
    index=$((index + 1))
  done
  exec "${argv[@]}"
}
