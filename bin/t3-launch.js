export const T3_LAUNCHER_NAME = CODEX_PROVIDER.launcherName;
export const LAUNCHER_HEADER = '# Generated by subc t3 install';

/**
 * Every file and directory the integration owns under the subc config dir.
 * The top-level keys are the Codex paths. `launcherFor`, `homeFor`, and
 * `underRoot` give the paths for any provider.
 */
export function t3Paths(configDir) {
  const root = path.join(configDir, 't3');
  const launcherFor = (provider) =>
    path.join(configDir, 'bin', provider.launcherName);
  const homeFor = (provider) =>
    provider.homeDir ? path.join(os.homedir(), provider.homeDir) : null;
  const underRoot = (relative) => path.join(root, ...relative.split('/'));
  return {
    configDir,
    launcher: launcherFor(CODEX_PROVIDER),
    root,
    // Written by subc 8.2.0 and read by nothing now. Uninstall removes it.
    state: path.join(root, 'state.json'),
    backups: path.join(root, 'backups'),
    codexHome: homeFor(CODEX_PROVIDER),
    catalogDir: underRoot('codex/catalog'),
    catalogFile: path.join(underRoot('codex/catalog'), 'model-catalog.json'),
    launcherFor,
    homeFor,
    underRoot,
  };
}

export class T3LaunchError extends Error {}

// Variables a caller sets to steer an ordinary subc launch: SUBCONSCIOUS_*
// (key, gateway, model, pinned catalog), SUBC_* (config dir, profile,
// metadata), and every input the provider's agent file declares (for Codex:
// CODEX_API_KEY, CODEX_EXTERNAL_TOOLS, CODEX_REASONING_EFFORT, and the rest).
// T3 Code starts the agent from its own environment. Any of these left in it
// would route or tune the provider in a way the default profile does not say.
const LAUNCH_OVERRIDE = /^(SUBC_|SUBCONSCIOUS_)/;
const isolatedNames = new WeakMap();

/** The exact names and the name prefixes that a provider's launch removes. */
function isolatedEnvFor(provider) {
  let names = isolatedNames.get(provider);
  if (!names) {
    const agent = agentById(provider.agentId);
    const exact = new Set((agent.inputs ?? []).map((input) => input.name));
    if (provider.isolateAgentOverrides) {
      for (const input of agent.inputs ?? [])
        for (const alias of input.aliases ?? []) exact.add(alias);
      for (const entry of agent.env ?? [])
        for (const name of entry.override ?? []) exact.add(name);
    }
    const prefixes = [];
    for (const name of provider.extraIsolatedEnv) {
      if (name.endsWith('*')) prefixes.push(name.slice(0, -1));
      else exact.add(name);
    }
    names = { exact, prefixes };
    isolatedNames.set(provider, names);
  }
  return names;
}

const defaultConfigDir = () => path.join(os.homedir(), '.subconscious');

/**
 * Drop launch overrides from `env` in place and point subc at `configDir`,
 * the config directory the launcher was installed for. The default directory
 * is left implicit, so subc reads it exactly as an ordinary launch does.
 */
export function isolateLaunchEnv(env, configDir, provider = CODEX_PROVIDER) {
  const { exact, prefixes } = isolatedEnvFor(provider);
  for (const name of Object.keys(env)) {
    if (
      LAUNCH_OVERRIDE.test(name) ||
      exact.has(name) ||
      prefixes.some((prefix) => name.startsWith(prefix))
    )
      delete env[name];
  }
  if (path.resolve(configDir) !== defaultConfigDir())
    env.SUBC_CONFIG_DIR = configDir;
  return env;
}

/**
 * Run `restart` (the SYSTEM_CA re-exec) with the caller's original env, since
 * the child recomputes everything and isolates its own env. True when the
 * child ran. When the restart fails, this process continues the launch, so
 * the env is isolated again first: the caller's SUBCONSCIOUS_* variables and
 * the provider's inputs must not steer it.
 */
export async function restartWithCallerEnv({
  env,
  original,
  configDir,
  restart,
  provider = CODEX_PROVIDER,
}) {
  for (const name of Object.keys(env)) delete env[name];
  Object.assign(env, original);
  if (await restart()) return true;
  for (const name of Object.keys(env)) delete env[name];
  Object.assign(env, original);
  isolateLaunchEnv(env, configDir, provider);
  return false;
}

function gatewayOrigin(baseUrl) {
  try {
    return new URL(baseUrl).origin;
  } catch {
    return 'the configured gateway';
  }
}

// The longest a launch waits for the catalog. T3 Code allows 30 s for an
// OpenCode helper to start and 25 s for a Claude probe.
const T3_CATALOG_DEADLINE_MS = 4000;

/**
 * Resolve the launch of the agent `agentId` from the default profile alone:
 * its saved key, its gateway, and the key-scoped catalog. The public list,
 * the packaged list, and a pinned list are all refused, so the agent never
 * starts on a catalog the key was not checked against. Call isolateLaunchEnv
 * first.
 */
export async function resolveT3Launch({ agentId = 'codex', ...options } = {}) {
  const [data, agents, profiles, models, network] = await Promise.all([
    import('./agent-data.js'),
    import('./agents.js'),
    import('./profiles.js'),
    import('./models.js'),
    import('./network.js'),
  ]);
  const agent = data.agentById(agentId);
  const profile = await profiles.loadProfile(profiles.DEFAULT_PROFILE);
  const auth = await agents.getAgentApiKey(profile, agent);
  if (!auth?.key)
    throw new T3LaunchError(
      'The default subc profile has no saved API key. Run subc login, then retry.',
    );
  const baseUrl = agents.launchGatewayUrl(profile);
  const origin = gatewayOrigin(baseUrl);
  const { model: requested, modelSource } = agents.extractModel([], profile);
  // When the key-scoped fetch fails, resolveModelCatalog also asks for the
  // public list, so a slow gateway could hold the launch for two fetch
  // timeouts. The deadline keeps the whole lookup inside 4 s.
  const deadline = AbortSignal.timeout(T3_CATALOG_DEADLINE_MS);
  let catalog;
  try {
    catalog = await models.resolveModelCatalog({
      baseUrl,
      apiKey: auth.key,
      selectedModel: requested,
      fallbackModels: data.PACKAGED_MODELS,
      signal: deadline,
      ...(options.fetchImpl ? { fetchImpl: options.fetchImpl } : {}),
    });
  } catch (error) {
    if (!deadline.aborted) throw error;
    throw new T3LaunchError(
      `Could not read the model catalog from ${origin} within ${T3_CATALOG_DEADLINE_MS / 1000} s.`,
    );
  }
  if (catalog.source !== 'catalog') {
    const why =
      catalog.source === 'public'
        ? `${origin} did not return the model catalog for this key. Check the key with subc whoami.`
        : `Could not read the model catalog from ${origin}: ${network.describeFailure(catalog.error)}`;
    throw new T3LaunchError(why);
  }
  const model = agents.selectLaunchModel(requested, modelSource, catalog);
  return { agent, profile, apiKey: auth.key, baseUrl, model, catalog };
}

async function privateDir(dir) {
  await fs.mkdir(dir, { recursive: true, mode: 0o700 });
  const stat = await fs.lstat(dir);
  const uid = process.getuid?.();
  if (!stat.isDirectory() || (uid !== undefined && stat.uid !== uid))
    throw new T3LaunchError(`${dir} is not a directory owned by you`);
  if ((stat.mode & 0o077) !== 0) await fs.chmod(dir, 0o700);
}

// run.sh renames a temp file over the catalog. A probe killed between the two
// leaves the temp file, so old ones are removed before the next launch.
const STALE_CATALOG_MS = 60_000;

async function removeStaleCatalogTemps(dir) {
  const now = Date.now();
  for (const name of await fs.readdir(dir)) {
    if (!name.startsWith('.catalog.')) continue;
    const file = path.join(dir, name);
    try {
      if (now - (await fs.lstat(file)).mtimeMs > STALE_CATALOG_MS)
        await fs.rm(file, { force: true });
    } catch {
      // Another launch removed it first.
    }
  }
}

/**
 * The command the launcher execs for an app-server or exec launch: the
 * Codex runbook, with the args T3 passed kept in order after the root
 * Subconscious config.
 */
export async function t3CodexPlan({ args, codexPath, paths, launch }) {
  const [{ runbookEnv }, { launchPlan }, { planCommand }] = await Promise.all([
    import('./agents.js'),
    import('./agent-launch.js'),
    import('./agent-spawn.js'),
  ]);
  const binDir = path.dirname(codexPath);
  const env = runbookEnv(
    launch.apiKey,
    launch.model,
    binDir,
    launch.profile,
    launch.agent,
    launch.catalog.defaultModels,
    launch.catalog.entries,
  );
  // A leading `--` stops subc flag parsing, so every word T3 sent reaches
  // Codex unchanged.
  const plan = launchPlan(launch.agent, { env, args: ['--', ...args] });
  const command = planCommand(launch.agent, plan, binDir);
  await privateDir(paths.catalogDir);
  await removeStaleCatalogTemps(paths.catalogDir);
  // The provider reads its key from SUBCONSCIOUS_API_KEY through env_key.
  // CODEX_API_KEY is Codex's credential for OpenAI, so a launch arg that
  // switched the provider back to OpenAI must not find the Subconscious key
  // there.
  const { CODEX_API_KEY: _openaiKey, ...codexEnv } = command.env;
  // run.sh is a bash script, and its stdout is the app-server protocol.
  for (const name of SHELL_STARTUP_ENV) delete codexEnv[name];
  return {
    argv: [command.file, ...command.args],
    env: {
      ...codexEnv,
      SUBC_CODEX_PROTOCOL_LAUNCH: '1',
      SUBC_CODEX_CATALOG_FILE: paths.catalogFile,
    },
    unset: SHELL_STARTUP_ENV,
  };
}

// The only two variables that carry the key into Claude Code: the bearer
// credential for /v1/messages and the header for OTEL log export.
const CLAUDE_KEY_CARRIERS = new Set([
  'ANTHROPIC_AUTH_TOKEN',
  'OTEL_EXPORTER_OTLP_HEADERS',
]);
// Copies of the key, the catalog, or the picker that runbookEnv adds for an
// ordinary subc claude launch. Claude Code reads none of them.
const CLAUDE_LAUNCH_EXTRAS = Object.freeze([
  'API_KEY',
  'CLAUDE_CODE_API_KEY',
  'SUBC_CLAUDE_SETTINGS',
  'SUBCONSCIOUS_MODELS',
  'SUBC_MODEL_METADATA',
]);

/**
 * Replace each `--model` value that is not in the catalog with `model`. The
 * flag wins over ANTHROPIC_MODEL in Claude Code, so the argv itself must
 * name a model the key can call. Returns the new args and the first model
 * that was replaced, or null.
 */
export function pinClaudeModel(args, catalog, model) {
  const next = [];
  let replaced = null;
  const pick = (value) => {
    if (catalog.includes(value)) return value;
    replaced ??= value;
    return model;
  };
  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (arg === '--') {
      next.push(...args.slice(i));
      break;
    }
    if (arg === '--model' && i + 1 < args.length) {
      next.push(arg, pick(args[++i]));
    } else if (arg.startsWith('--model=')) {
      next.push(`--model=${pick(arg.slice('--model='.length))}`);
    } else {
      next.push(arg);
    }
  }
  return { args: next, replaced };
}

const SETTINGS_UNREADABLE =
  'T3 Code passed a --settings value that is not a JSON object, or a file that does not hold one. The value is not shown, because it can hold secrets.';

function readSettingsValue(value, cwd) {
  const text = value.trim();
  let parsed;
  try {
    parsed = JSON.parse(
      text.startsWith('{')
        ? text
        : readFileSync(path.resolve(cwd, value), 'utf8'),
    );
  } catch {
    throw new T3LaunchError(SETTINGS_UNREADABLE);
  }
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed))
    throw new T3LaunchError(SETTINGS_UNREADABLE);
  return parsed;
}

/**
 * Merge `picker` into the last `--settings` value in `args`, and drop the
 * earlier ones, so Claude Code gets exactly one `--settings`. Claude Code
 * keeps only the last flag, so a second flag beside T3 Code's would drop
 * either T3 Code's keys or the picker. A value that starts with `{` is
 * inline JSON, and any other value is a file path relative to `cwd`. With
 * no `--settings` in `args`, one is added before any `--`.
 */
export function mergeClaudeSettings(args, picker, cwd = process.cwd()) {
  const flags = [];
  let end = args.length;
  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (arg === '--') {
      end = i;
      break;
    }
    if (arg === '--settings') {
      if (i + 1 >= args.length) throw new T3LaunchError(SETTINGS_UNREADABLE);
      flags.push({ index: i, words: 2, value: args[i + 1] });
      i++;
    } else if (arg.startsWith('--settings=')) {
      flags.push({ index: i, words: 1, value: arg.slice(11) });
    }
  }
  if (!flags.length)
    return [
      ...args.slice(0, end),
      '--settings',
      JSON.stringify(picker),
      ...args.slice(end),
    ];
  const last = flags.at(-1);
  const merged = JSON.stringify({
    ...readSettingsValue(last.value, cwd),
    ...picker,
  });
  const drop = new Set();
  for (const flag of flags)
    for (let word = 0; word < flag.words; word++) drop.add(flag.index + word);
  const next = [];
  for (let i = 0; i < args.length; i++) {
    if (i === last.index) next.push('--settings', merged);
    else if (!drop.has(i)) next.push(args[i]);
  }
  return next;
}

/**
 * The command the launcher execs for a Claude Code protocol launch: the
 * claude-code runbook, as subc claude builds it, with T3 Code's args kept
 * in order. Three changes make it fit T3 Code:
 *
 * - The template's own `--settings` picker is merged into T3 Code's last
 *   `--settings` value.
 * - A `--model` outside the key-scoped catalog becomes the profile model.
 * - Only ANTHROPIC_AUTH_TOKEN and OTEL_EXPORTER_OTLP_HEADERS carry the key.
 *
 * `fallback` names the replaced model, or is null.
 */
export async function t3ClaudePlan({
  args,
  claudePath,
  launch,
  cwd = process.cwd(),
}) {
  const [{ runbookEnv }, { launchPlan }, { planCommand }] = await Promise.all([
    import('./agents.js'),
    import('./agent-launch.js'),
    import('./agent-spawn.js'),
  ]);
  const binDir = path.dirname(claudePath);
  const env = runbookEnv(
    launch.apiKey,
    launch.model,
    binDir,
    launch.profile,
    launch.agent,
    launch.catalog.defaultModels,
    launch.catalog.entries,
  );
  const pinned = pinClaudeModel(args, launch.catalog.models, launch.model);
  // A leading `--` stops subc flag parsing, so every word T3 Code sent
  // reaches Claude Code.
  const plan = launchPlan(launch.agent, {
    env,
    args: ['--', ...pinned.args],
  });
  const command = planCommand(launch.agent, plan, binDir);
  // The template starts with `--settings PICKER`. It is merged below instead.
  if (command.args[0] !== '--settings')
    throw new T3LaunchError(
      'The claude-code launch template no longer starts with --settings. Update subc.',
    );
  const picker = JSON.parse(command.args[1]);
  const claudeEnv = { ...command.env };
  for (const name of CLAUDE_LAUNCH_EXTRAS) delete claudeEnv[name];
  // A profile value can hold another copy of the key, such as an
  // OPENCODE_API_KEY line. Every tool Claude Code runs inherits this env.
  for (const [name, value] of Object.entries(claudeEnv))
    if (value === launch.apiKey && !CLAUDE_KEY_CARRIERS.has(name))
      delete claudeEnv[name];
  return {
    argv: [
      claudePath,
      ...mergeClaudeSettings(command.args.slice(2), picker, cwd),
    ],
    env: claudeEnv,
    fallback: pinned.replaced
      ? { requested: pinned.replaced, model: launch.model }
      : null,
  };
}

// Values that runbookEnv adds for an ordinary subc opencode launch, which
// the launch config already holds. OpenCode reads none of them, and every
// tool that the OpenCode helper runs would inherit them.
const OPENCODE_LAUNCH_EXTRAS = Object.freeze([
  'API_KEY',
  'GATEWAY_URL',
  'MODEL',
  'SUBCONSCIOUS_MODELS',
  'SUBC_MODEL_METADATA',
  'OPENCODE_CONTEXT_LIMIT',
  'OPENCODE_OUTPUT_LIMIT',
]);

/**
 * The command the launcher execs for an `opencode serve` launch: the
 * opencode runbook, as subc opencode builds it, with T3 Code's serve args
 * kept in order at the end. OPENCODE_CONFIG_CONTENT holds the whole launch
 * config, with `enabled_providers: ["subconscious"]`.
 *
 * run.sh passes `serve` through unchanged, without `--standalone`. That is
 * right for T3 Code: `opencode serve` without `--service` is a private
 * server with its own env and config, and it never starts or joins
 * OpenCode's shared background service. `--standalone` exists for the TUI
 * and `run`, which are clients that would otherwise use that service. run.sh
 * execs OpenCode, so the process T3 Code started becomes `opencode serve`,
 * and its command line ends with T3 Code's serve args, which T3 Code's
 * orphan reaper matches.
 *
 * Only SUBCONSCIOUS_API_KEY carries the key. The config reads it through
 * `{env:SUBCONSCIOUS_API_KEY}`.
 */
export async function t3OpenCodePlan({ args, opencodePath, launch }) {
  const [{ runbookEnv }, { launchPlan }, { planCommand }] = await Promise.all([
    import('./agents.js'),
    import('./agent-launch.js'),
    import('./agent-spawn.js'),
  ]);
  const binDir = path.dirname(opencodePath);
  const env = runbookEnv(
    launch.apiKey,
    launch.model,
    binDir,
    launch.profile,
    launch.agent,
    launch.catalog.defaultModels,
    launch.catalog.entries,
  );
  // A leading `--` stops subc flag parsing, so every word T3 Code sent
  // reaches OpenCode unchanged.
  const plan = launchPlan(launch.agent, { env, args: ['--', ...args] });
  const command = planCommand(launch.agent, plan, binDir);
  // run.sh gets `opencode` and T3 Code's args, and execs them unchanged.
  const expected = ['opencode', ...args];
  const passed = command.args.slice(1);
  if (
    passed.length !== expected.length ||
    passed.some((word, i) => word !== expected[i])
  )
    throw new T3LaunchError(
      'The opencode launch template no longer passes the serve args through unchanged. Update subc.',
    );
  const openCodeEnv = { ...command.env };
  for (const name of OPENCODE_LAUNCH_EXTRAS) delete openCodeEnv[name];
  // A profile value can hold another copy of the key, such as an
  // OPENCODE_API_KEY line under another name.
  for (const [name, value] of Object.entries(openCodeEnv))
    if (value === launch.apiKey && name !== 'SUBCONSCIOUS_API_KEY')
      delete openCodeEnv[name];
  // run.sh is a bash script, and T3 Code reads the helper's stdout.
  for (const name of SHELL_STARTUP_ENV) delete openCodeEnv[name];
  return {
    argv: [command.file, ...command.args],
    env: openCodeEnv,
    unset: SHELL_STARTUP_ENV,
    // The helper is long-lived, so the launcher starts its watchdog.
    watch: true,
  };
}

export function shellQuote(value) {
  const text = String(value);
  if (/[\0\n\r]/.test(text))
    throw new T3LaunchError(`Path cannot contain a newline: ${text}`);
  return `'${text.replaceAll("'", "'\\''")}'`;
}

/**
 * The launcher's first line. Bash sources the file in BASH_ENV before it
 * reads a script, and stdout is T3 Code's protocol stream, so a BASH_ENV
 * that prints would break the session before the script's first command
 * runs. Privileged mode (`-p`) makes bash skip BASH_ENV and ENV, and also
 * skip shell functions and SHELLOPTS from the env. `env -S` splits the two
 * words, because a shebang passes one argument.
 */
export const LAUNCHER_SHEBANG = '#!/usr/bin/env -S bash -p';

// The descriptor values that the launcher writes into shell code unquoted.
const SHELL_NAME = /^[a-z][a-z0-9_]*$/;
const LAUNCHER_WORD = /^[a-z0-9][a-z0-9-]*$/;
const ADAPTER_FLAG = /^--[a-z][a-z-]*$/;

/**
 * The name the watchdog runs under, as its `$0`. Status finds the running
 * helpers by this name and the config dir after it.
 */
export function watchdogName(provider) {
  return `${provider.launcherName}-watchdog`;
}

/**
 * A background check, started just before the exec, for an agent that T3
 * Code runs as a long-lived helper. The adapter asks for it with a `watch`
 * record, and only for a launch that starts such a helper, so a short
 * passthrough such as `--version` leaves no watchdog behind.
 *
 * Every 2 s it checks the process that T3 Code started. When that process
 * now has another parent, T3 Code's server is gone, so the check sends it
 * SIGTERM. The check ends when the process ends. Its stdio is /dev/null, so
 * it never holds T3 Code's pipes open.
 *
 * The plan has exported the key by now. `env -i` starts the check in a new
 * bash with PATH alone, so neither the check nor its `sleep` and `ps`
 * children hold the key or any other launch value.
 */
function watchdog(provider) {
  return `if [ "$subc_watch" = 1 ]; then
  subc_helper=$$
  subc_parent=$PPID
  /usr/bin/env -i PATH="$PATH" "$BASH" -p -c '
    while sleep 2; do
      kill -0 "$1" 2>/dev/null || exit 0
      if [ "$(ps -o ppid= -p "$1" 2>/dev/null | tr -d " ")" != "$2" ]; then
        kill -TERM "$1" 2>/dev/null
        exit 0
      fi
    done
  ' ${watchdogName(provider)} "$subc_helper" "$subc_parent" "$subc_config_dir" </dev/null >/dev/null 2>&1 &
fi
`;
}

/**
 * The launcher T3 Code runs as the provider's agent binary. It pins this
 * Node, this package's adapter, the agent binary, and the config directory.
 * Node only computes the plan; the shell applies it and execs, so the
 * process T3 started becomes the agent and a kill from T3 reaches the agent
 * itself.
 */
export function launcherScript({
  provider = CODEX_PROVIDER,
  node,
  adapter,
  binary,
  configDir,
  version,
}) {
  const { binaryName: name, launcherName, binaryFlag } = provider;
  if (
    !SHELL_NAME.test(name) ||
    !LAUNCHER_WORD.test(launcherName) ||
    !ADAPTER_FLAG.test(binaryFlag)
  )
    throw new T3LaunchError(
      `Provider ${provider.id} has unsafe launcher names`,
    );
  return `${LAUNCHER_SHEBANG}
${LAUNCHER_HEADER} (subconscious-cli ${version}). Do not edit.
# Run subc t3 install to refresh it, or subc t3 uninstall to remove it.
#
# T3 Code runs this file as the ${provider.label} binary of its "${provider.displayName}"
# provider. The adapter prints how to start ${provider.label} as NUL-separated records:
#   env NAME=VALUE | unset NAME | arg WORD | ${provider.watchdog ? 'watch | ' : ''}ok
# This shell applies them and execs, so no Node process stays behind.
unset BASH_ENV ENV
set -u
subc_node=${shellQuote(node)}
subc_adapter=${shellQuote(adapter)}
subc_${name}=${shellQuote(binary)}
subc_config_dir=${shellQuote(configDir)}
for subc_path in "$subc_node" "$subc_adapter" "$subc_${name}"; do
  if [ ! -e "$subc_path" ]; then
    printf '${launcherName}: %s is missing. Run subc t3 install again.\\n' "$subc_path" >&2
    exit 69
  fi
done
subc_argv=()
subc_ok=0
${provider.watchdog ? 'subc_watch=0\n' : ''}while IFS= read -r -d '' subc_kind; do
  IFS= read -r -d '' subc_value || exit 70
  case "$subc_kind" in
    env) export -- "$subc_value" ;;
    unset) unset -v -- "$subc_value" ;;
    arg) subc_argv+=("$subc_value") ;;
    ok) subc_ok=1 ;;
${provider.watchdog ? '    watch) subc_watch=1 ;;\n' : ''}    *) exit 70 ;;
  esac
done < <("$subc_node" "$subc_adapter" ${binaryFlag} "$subc_${name}" --config-dir "$subc_config_dir" -- "$@" </dev/null)
if [ "$subc_ok" != 1 ] || [ "\${#subc_argv[@]}" -eq 0 ]; then
  exit 1
fi
${provider.watchdog ? watchdog(provider) : ''}exec "\${subc_argv[@]}"
`;
}
