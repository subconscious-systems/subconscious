#!/usr/bin/env bash
# Surgical Codex hook merge/unmerge. Sourced by install.sh and run.sh.
# Never reads, writes, or deletes ~/.codex/config.toml.

CODEX_DIR="${CODEX_DIR:-${HOME}/.codex}"
HOOKS_JSON="${HOOKS_JSON:-${CODEX_DIR}/hooks.json}"
HOOK_DST="${HOOK_DST:-${CODEX_DIR}/subconscious-hook.sh}"
HOOKS_ENV_FILE="${HOOKS_ENV_FILE:-${CODEX_DIR}/subconscious-hooks.env}"
MARKER="${MARKER:-subconscious-hook.sh}"

codex_hooks_have_jq() {
  command -v jq >/dev/null 2>&1
}

codex_hooks_json_valid() {
  [[ -f "$HOOKS_JSON" ]] && jq -e . "$HOOKS_JSON" >/dev/null 2>&1
}

codex_strip_hook_entries() {
  local tmp
  tmp="$(mktemp)"
  jq --arg marker "$MARKER" '
    def strip:
      (. // [])
      | map(
          .hooks = ((.hooks // []) | map(select((.command // "") | tostring | contains($marker) | not)))
        )
      | map(select((.hooks | length) > 0));
    .hooks = (.hooks // {})
    | .hooks |= with_entries(.value |= strip)
  ' "$HOOKS_JSON" >"$tmp"
  mv "$tmp" "$HOOKS_JSON"
}

codex_append_hook_groups() {
  local tmp
  tmp="$(mktemp)"
  jq --arg cmd "$HOOK_DST" '
    def group($msg):
      [{ "hooks": [{ "type": "command", "command": $cmd, "timeout": 3, "statusMessage": $msg }] }];
    .hooks = (.hooks // {})
    | .hooks.PreCompact = ((.hooks.PreCompact // []) + group("Reporting compaction start"))
    | .hooks.PostCompact = ((.hooks.PostCompact // []) + group("Reporting compaction end"))
  ' "$HOOKS_JSON" >"$tmp"
  mv "$tmp" "$HOOKS_JSON"
}

codex_write_hook_script() {
  mkdir -p "$CODEX_DIR"
  cp "$HOOK_SRC" "$HOOK_DST"
  chmod +x "$HOOK_DST"
}

codex_write_hooks_env() {
  umask 077
  cat >"$HOOKS_ENV_FILE" <<EOF
# Generated by subconscious-cli Codex integration — do not commit secrets.
export SUBCONSCIOUS_GATEWAY_URL='${GATEWAY_URL%/}'
export SUBCONSCIOUS_API_KEY='${API_KEY}'
EOF
  chmod 600 "$HOOKS_ENV_FILE"
}

# codex_ensure_hooks [strict|best-effort]
codex_ensure_hooks() {
  local mode="${1:-strict}"
  if ! codex_hooks_have_jq; then
    echo "warning: jq is required to merge Codex hooks without overwriting ~/.codex/hooks.json" >&2
    if [[ "$mode" == "strict" ]]; then
      echo "missing required command: jq" >&2
      return 1
    fi
    return 0
  fi
  if [[ -z "${GATEWAY_URL:-}" || -z "${API_KEY:-}" ]]; then
    echo "--gateway-url and --api-key are required to install Codex hooks" >&2
    return 1
  fi
  if [[ -z "${HOOK_SRC:-}" || ! -f "$HOOK_SRC" ]]; then
    echo "warning: Codex hook script missing; skipping hooks" >&2
    return 0
  fi
  mkdir -p "$CODEX_DIR"
  if [[ -f "$HOOKS_JSON" ]] && ! codex_hooks_json_valid; then
    echo "warning: ${HOOKS_JSON} is not valid JSON; leaving it unchanged" >&2
    if [[ "$mode" == "strict" ]]; then
      return 1
    fi
    return 0
  fi
  if [[ ! -f "$HOOKS_JSON" ]]; then
    printf '%s\n' '{"hooks":{}}' >"$HOOKS_JSON"
  fi
  codex_write_hook_script
  codex_write_hooks_env
  codex_strip_hook_entries
  codex_append_hook_groups
  echo "Merged Subconscious Codex hooks into $HOOKS_JSON"
  echo "Trust new hooks in Codex with /hooks (or --dangerously-bypass-hook-trust)."
}

codex_uninstall_hooks() {
  if [[ -f "$HOOKS_JSON" ]] && codex_hooks_have_jq && codex_hooks_json_valid; then
    codex_strip_hook_entries
    echo "Removed Subconscious entries from $HOOKS_JSON"
  elif [[ -f "$HOOKS_JSON" ]]; then
    echo "warning: ${HOOKS_JSON} is not valid JSON; leaving it unchanged" >&2
  else
    echo "No Codex hooks.json at $HOOKS_JSON"
  fi
  rm -f "$HOOK_DST" "$HOOKS_ENV_FILE"
  rm -f "${CODEX_DIR}/subconscious.env"
}

codex_hooks_status() {
  echo "scope: user"
  echo "codex dir: $CODEX_DIR"
  echo "hooks.json: $HOOKS_JSON"
  if [[ -f "$HOOKS_JSON" ]] && codex_hooks_have_jq && jq -e --arg m "$MARKER" '
      [.hooks[]?[]?.hooks[]? | select((.command // "") | tostring | contains($m))] | length > 0
    ' "$HOOKS_JSON" >/dev/null 2>&1; then
    echo "hooks: installed"
  else
    echo "hooks: not installed"
  fi
  if [[ -x "$HOOK_DST" ]]; then
    echo "hook script: $HOOK_DST (executable)"
  else
    echo "hook script: missing"
  fi
  if [[ -f "$HOOKS_ENV_FILE" ]]; then
    echo "env: $HOOKS_ENV_FILE (present)"
  else
    echo "env: missing"
  fi
  if [[ -f "${CODEX_DIR}/config.toml" ]] && grep -q 'model_provider = "subconscious"' "${CODEX_DIR}/config.toml" 2>/dev/null; then
    echo "legacy config.toml: contains a Subconscious provider (this CLI no longer manages that file)"
  fi
}
